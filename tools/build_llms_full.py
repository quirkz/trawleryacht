#!/usr/bin/env python3
"""Regenerate llms-full.txt and run consistency checks on the trawleryacht site.

Run from anywhere:

    python3 tools/build_llms_full.py

It rewrites ``llms-full.txt`` (the single-fetch text bundle) and verifies that the
HTML page, the Markdown twins and the JSON facts agree on the things that matter.
Exit code 0 means everything passed; 1 means something needs fixing.
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BASE = "https://quirkz.github.io/trawleryacht/"

# Markdown files that make up the bundle, in reading order.
SOURCES = ["index.md", "specifications.md", "features.md", "glossary.md"]

# Phrases that must appear (case-insensitively) in both index.html and index.md.
REQUIRED_PHRASES = [
    "full-displacement trawler yacht",
    "44 ft",
    "13.4 m",
    "steel",
    "ISO/CE Category A",
    "Cummins 6.7",
    "250 hp",
    "8 knots at 1,800 rpm",
    "approaching 1,000",
    "low-profile flybridge",
    "folding radar arch",
    "AwlGrip",
    "AwlCraft",
    "white metal",
    "Great Loop",
]

# Phrases that would overstate what the builder has published.
FORBIDDEN_PHRASES = [
    "category a certified",
    "ce certified",
    "1,000-mile range",
    "1000-mile range",
    "guaranteed range",
    "unlimited range",
]

ALLOWED_CONFIDENCE = {"stated", "derived", "target", "not_published"}

errors: list[str] = []
warnings: list[str] = []


def fail(message: str) -> None:
    errors.append(message)


def warn(message: str) -> None:
    warnings.append(message)


def read(path: str) -> str:
    return (ROOT / path).read_text(encoding="utf-8")


def check_sources_exist() -> None:
    for name in SOURCES + ["llms.txt", "data/boat.json", "index.html"]:
        if not (ROOT / name).is_file():
            fail(f"missing file: {name}")


def check_prose() -> None:
    html = read("index.html").lower()
    md = read("index.md").lower()

    for phrase in REQUIRED_PHRASES:
        needle = phrase.lower()
        for label, text in (("index.html", html), ("index.md", md)):
            if needle not in text:
                fail(f"{label}: required phrase missing: {phrase!r}")

    for phrase in FORBIDDEN_PHRASES:
        for label, text in (("index.html", html), ("index.md", md)):
            if phrase in text:
                fail(f"{label}: forbidden phrase present: {phrase!r}")


def check_json() -> dict:
    data = json.loads(read("data/boat.json"))

    allowed = ALLOWED_CONFIDENCE
    for fact in data.get("facts", []):
        if fact.get("confidence") not in allowed:
            fail(f"data/boat.json: fact {fact.get('id')!r} has confidence {fact.get('confidence')!r}")

    derived = {item["id"]: item for item in data.get("derived", [])}
    expected = {
        "loa_metres": 13.41,
        "range_km": 1852,
        "range_miles": 1151,
        "running_hours": 125,
        "cruise_kmh": 14.8,
        "cruise_mph": 9.2,
    }
    for key, value in expected.items():
        if key not in derived:
            fail(f"data/boat.json: derived figure missing: {key}")
        elif abs(float(derived[key]["value"]) - value) > 0.051:
            fail(f"data/boat.json: derived figure {key} should be {value}")

    if data.get("meta", {}).get("last_updated") is None:
        fail("data/boat.json: meta.last_updated is missing")

    if not data.get("not_published"):
        fail("data/boat.json: not_published list is empty")

    return data


def check_llms_links() -> None:
    text = read("llms.txt")
    for match in re.finditer(r"\]\((" + re.escape(BASE) + r"[^)\s]*)\)", text):
        url = match.group(1)
        rel = url[len(BASE):].split("#")[0]
        if rel == "llms-full.txt":
            continue  # generated by this script
        if rel and not (ROOT / rel).exists():
            fail(f"llms.txt: link target does not exist: {rel}")


def check_date_consistency(data: dict) -> None:
    expected = data["meta"]["last_updated"]
    html = read("index.html")
    if expected not in html:
        fail(f"index.html: last-updated date {expected} not found")
    sitemap = read("sitemap.xml")
    if expected not in sitemap:
        fail(f"sitemap.xml: lastmod {expected} not found")


def build_bundle(data: dict) -> None:
    updated = data["meta"]["last_updated"]
    parts = [
        "# Trawler Yacht — complete text bundle",
        "",
        "> Generated file. Rebuild with `python3 tools/build_llms_full.py`; do not edit by hand.",
        f"> Last updated: {updated} · Canonical page: {BASE}",
        "",
        "Every Markdown file on the site, concatenated so an agent can read the whole thing in",
        "one fetch. Start with `llms.txt` if you only need an index; start here if you need the",
        "full detail, including the confidence labels and the list of figures not published.",
        "",
    ]

    for name in SOURCES:
        body = read(name).rstrip() + "\n"
        parts += [
            "",
            "---",
            "",
            f"<!-- source: {name} — {BASE}{name} -->",
            "",
            body,
        ]

    out = ROOT / "llms-full.txt"
    out.write_text("\n".join(parts), encoding="utf-8")
    size = out.stat().st_size
    print(f"wrote llms-full.txt ({size:,} bytes, {len(SOURCES)} documents)")


def main() -> int:
    check_sources_exist()
    check_prose()
    data = check_json()
    check_llms_links()
    check_date_consistency(data)

    for message in warnings:
        print(f"warning: {message}")
    for message in errors:
        print(f"error: {message}")

    if errors:
        print(f"\n{len(errors)} problem(s) found; llms-full.txt not rebuilt.")
        return 1

    build_bundle(data)
    print("checks passed")
    return 0


if __name__ == "__main__":
    sys.exit(main())
